/**
 * Regenerate where each place of each layout falls, from the reference.
 *
 *   pnpm gen:face
 *
 * Run this only when you mean to move a place. The `git diff` of
 * `contract/fixtures/face/layout.expected.json` shows exactly what moved, and
 * the tablet's parity test fails until `FaceLayout.kt` moves with it.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { LAYOUTS, placeBox, placeFace, placeZones } from "../src/index.ts";

const DIR = fileURLToPath(new URL("../../../contract/fixtures/face/", import.meta.url));

export interface LayoutKeys {
  keys: { name: string; w: number; h: number; unit: number }[];
}

export function expected(input: LayoutKeys) {
  return {
    about: "Generated by `pnpm gen:face` from packages/face. Do not edit.",
    keys: input.keys.map((key) => ({
      ...key,
      layouts: Object.fromEntries(LAYOUTS.map((layout) => [layout, placeFace(layout, key.w, key.h, key.unit)])),
      zones: placeZones(3, key.w, key.h, key.unit),
      box: placeBox({ x: 0.1, y: 0.25, w: 0.55, h: 0.333 }, key.w, key.h),
    })),
  };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const input = JSON.parse(readFileSync(`${DIR}layout.json`, "utf8")) as LayoutKeys;
  writeFileSync(`${DIR}layout.expected.json`, `${JSON.stringify(expected(input), null, 2)}\n`, "utf8");
  console.log("wrote layout.expected.json");
}
