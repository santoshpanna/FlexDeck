/**
 * Write the gallery's presets where the agent's tests read them:
 *
 *   pnpm gen:presets
 *
 * The agent checks every one parses — templates, rules, faces — so a preset
 * that would be refused on save never ships. The portal's tests fail while
 * this file and `presets.lib.ts` disagree.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { PRESETS } from "../src/modules/config/lib/presets.lib.ts";

export const PRESETS_FILE = fileURLToPath(new URL("../../../contract/fixtures/face/presets.json", import.meta.url));

export function presetsJson(): string {
  return `${JSON.stringify({ about: "Generated by `pnpm gen:presets` from apps/portal. Do not edit.", presets: PRESETS }, null, 2)}\n`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(PRESETS_FILE, presetsJson(), "utf8");
  console.log(`wrote ${PRESETS.length} presets`);
}
